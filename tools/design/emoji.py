#!/usr/bin/env python3
"""Generates Ladle's standard emoji table from the data apron-web's `:shortcode` list searches.

apron-web loads `@emoji-mart/data` (its `main`, sets/15/native.json) and searches every emoji's
shortcode, name, keywords and aliases (src/lib/ui/emoji-autocomplete.ts). This reads the same
file from the apron-web clone's node_modules (~/Developer/forks/apron-web; APRON_WEB overrides
it), refuses any version or content other than the pin in tools/design/UPSTREAM, and writes
Packages/ApronKit/Sources/ApronKit/StandardEmojiData.swift: one line per emoji with a glyph,
`shortcode<TAB>glyph<TAB>name<TAB>keyword|alias|...`, in the order apron-web's ties fall
(`id.localeCompare`, ICU's root order, which puts `_` before `-` before `+` before digits and
letters; ids use no other characters, and the script fails if one does).

    tools/design/emoji.py           write the table
    tools/design/emoji.py --check   exit 1 if it differs from a fresh generation

Move the pin after `bun install` brings a new @emoji-mart/data into the clone: review what
changed, put the new version and the file's SHA-256 in UPSTREAM, rerun, and update the
literal search results StandardEmojiTests holds.
"""
import hashlib
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PIN = ROOT / "tools/design/UPSTREAM"
OUT = ROOT / "Packages/ApronKit/Sources/ApronKit/StandardEmojiData.swift"
WEB = Path(os.environ.get("APRON_WEB", Path.home() / "Developer/forks/apron-web"))
PACKAGE = WEB / "node_modules/@emoji-mart/data"
# ICU root collation of the characters shortcodes use, as `localeCompare` orders them.
ORDER = "_-+0123456789abcdefghijklmnopqrstuvwxyz"


def pin():
    for line in PIN.read_text().splitlines():
        if line.startswith("@emoji-mart/data "):
            _, version, digest = line.split()
            return version, digest
    sys.exit("emoji.py: no '@emoji-mart/data <version> <sha256>' line in " + str(PIN))


def load():
    version, digest = pin()
    manifest = PACKAGE / "package.json"
    if not manifest.exists():
        sys.exit(f"emoji.py: no {manifest}; run `bun install` in {WEB}, or set APRON_WEB")
    found = json.loads(manifest.read_text())["version"]
    if found != version:
        sys.exit(f"emoji.py: {PACKAGE} is {found}, the pin is {version}; review the new data and move the pin")
    source = PACKAGE / json.loads(manifest.read_text())["main"]
    raw = source.read_bytes()
    if hashlib.sha256(raw).hexdigest() != digest:
        sys.exit(f"emoji.py: {source} differs from the pinned SHA-256 for {version}")
    return version, json.loads(raw)


def collation_key(shortcode):
    if any(c not in ORDER for c in shortcode):
        sys.exit(f"emoji.py: shortcode {shortcode!r} has a character outside {ORDER!r}; extend ORDER from ICU's root order")
    return [ORDER.index(c) for c in shortcode]


def field(text):
    if "\t" in text or "|" in text or "\n" in text:
        sys.exit(f"emoji.py: {text!r} holds a tab, a bar or a line break, which the table uses")
    return text


def generate():
    version, data = load()
    aliases = {}
    for alias, shortcode in data["aliases"].items():
        aliases.setdefault(shortcode, []).append(alias)
    lines = []
    for shortcode in sorted(data["emojis"], key=collation_key):
        item = data["emojis"][shortcode]
        native = item["skins"][0].get("native") if item["skins"] else None
        if not native:
            continue
        terms = [field(term) for term in item["keywords"] + aliases.get(shortcode, [])]
        lines.append("\t".join([field(shortcode), field(native), field(item["name"]), "|".join(terms)]))
    body = "\n".join(lines)
    return f'''// Generated by tools/design/emoji.py from @emoji-mart/data {version}. Do not edit.

enum StandardEmojiData {{
    static let version = "{version}"

    /// `shortcode<TAB>glyph<TAB>name<TAB>keyword|alias|...` per line, in apron-web's tie order.
    static let table = #"""
{body}
"""#
}}
'''


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"emoji.py: {OUT.relative_to(ROOT)} differs from a fresh generation; run tools/design/emoji.py")
        print(f"emoji.py: {OUT.relative_to(ROOT)} matches @emoji-mart/data at the pin")
        return
    OUT.write_text(text)
    print(f"emoji.py: wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
