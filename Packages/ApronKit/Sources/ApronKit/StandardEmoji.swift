import Foundation

/// One row of the composer's `:` list, as apron-web's `EmojiSuggestion`: a standard emoji by its
/// shortcode, or a server's custom emoji (`ext:emoji`) by its key's name.
public struct EmojiSuggestion: Hashable, Sendable {
    /// The shortcode, or a custom emoji's name: its key without the colons.
    public let id: String
    public let name: String
    /// What picking it inserts: the emoji, or a custom emoji's key.
    public let inserted: String
    /// The custom emoji, drawn from its image.
    public let custom: CustomEmoji?

    public init(id: String, name: String, inserted: String, custom: CustomEmoji? = nil) {
        self.id = id
        self.name = name
        self.inserted = inserted
        self.custom = custom
    }

    public init(_ emoji: CustomEmoji) {
        self.init(id: String(emoji.key.dropFirst().dropLast()), name: emoji.alt ?? emoji.key, inserted: emoji.key, custom: emoji)
    }
}

/// The standard emoji a `:shortcode` finds, as apron-web's `searchEmoji` over `@emoji-mart/data`
/// (`StandardEmojiData`, generated by tools/design/emoji.py).
public enum StandardEmoji {
    /// The most rows the `:` list shows (apron-web's `MAX_MATCHES`).
    public static let rows = 8

    private struct Indexed: Sendable {
        let emoji: EmojiSuggestion
        /// The lowercased shortcode, then its name, keywords and aliases.
        let terms: [String]
    }

    /// Read once, on the first search, as apron-web indexes its data once.
    private static let index: [Indexed] = StandardEmojiData.table.split(separator: "\n").map { line in
        let fields = line.split(separator: "\t", omittingEmptySubsequences: false).map(String.init)
        let extra = fields[3].isEmpty ? [] : fields[3].split(separator: "|").map(String.init)
        return Indexed(emoji: EmojiSuggestion(id: fields[0], name: fields[2], inserted: fields[1]),
                       terms: ([fields[0], fields[2]] + extra).map { $0.lowercased() })
    }

    /// Shortcodes, names, aliases and keywords that match: the shortcode itself, then a whole
    /// term, then a term's start, then anywhere in one; ties in apron-web's order (`id.localeCompare`).
    public static func search(_ query: String) -> [EmojiSuggestion] {
        var needle = Substring(query.trimmingCharacters(in: .whitespacesAndNewlines).lowercased())
        if needle.hasPrefix(":") { needle = needle.dropFirst() }
        guard !needle.isEmpty else { return [] }
        let word = String(needle)
        var ranked: [(rank: Int, emoji: EmojiSuggestion)] = []
        for entry in index {
            let terms = entry.terms
            let rank = terms[0] == word ? 0 : terms.contains(word) ? 1 : terms.contains { $0.hasPrefix(word) } ? 2
                : terms.contains { $0.contains(word) } ? 3 : nil
            if let rank { ranked.append((rank, entry.emoji)) }
        }
        return ranked.enumerated().sorted { ($0.element.rank, $0.offset) < ($1.element.rank, $1.offset) }.prefix(rows).map(\.element.emoji)
    }

    /// The server's custom emoji the query finds (`EmojiCatalog.search`), ahead of the standard
    /// ones, together at most `rows`, as apron-web's `withCustomEmoji`. Picking one inserts its key.
    public static func suggestions(_ query: String, catalog: EmojiCatalog?) -> [EmojiSuggestion] {
        let custom = catalog?.search(query, limit: rows).map(EmojiSuggestion.init) ?? []
        return Array((custom + search(query)).prefix(rows))
    }

    /// The `:shortcode` the end of `text` types, as apron-web's `emojiQuery`: at least two and at
    /// most 32 of `A-Z a-z 0-9 _ + -` after a `:` at the start or after whitespace. One letter is
    /// an emoticon (`:D`), never a query.
    public static func query(in text: String) -> String? {
        let typed = text.reversed().prefix { $0.isASCII && ($0.isLetter || $0.isNumber || "_+-".contains($0)) }
        guard (2 ... 32).contains(typed.count) else { return nil }
        let rest = text.dropLast(typed.count)
        guard rest.last == ":" else { return nil }
        if let before = rest.dropLast().last, !before.isWhitespace { return nil }
        return String(typed.reversed())
    }
}
